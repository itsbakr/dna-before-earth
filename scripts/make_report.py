"""Build results/RESULTS.md from results/statistics.json and results/calibration.json.

Every number in the report is read from those files, so the text cannot drift from the code.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def f(x, d=2):
    return "none" if x is None else f"{x:.{d}f}"


def main():
    s = json.load(open(ROOT / "results" / "statistics.json"))
    c = json.load(open(ROOT / "results" / "calibration.json"))
    rep, eiv, rc, er = s["replication"], s["errors_in_variables"], s["rate_constancy"], s["early_rate"]
    L = []
    w = L.append

    w("# Results: replication, statistics and calibration of the genome-complexity clock\n")
    w("*Generated by `scripts/make_report.py` from `results/statistics.json` and "
      "`results/calibration.json`. Do not edit by hand; run `make reproduce`.*\n")

    w("## 1. Replication\n")
    p = rep["sharov_printed"]
    w(f"Sharov (2006) printed log10(y) = {p['a']} + {p['b']}x, R² = {p['r2']}, {p['fold_per_gyr']}-fold per Gyr.\n")
    w("| Dataset | n | Intercept | Rate (log10/Gyr) | R² | Fold per Gyr | Origin of 1 bp (Gya) | 95% Fieller | 99% Fieller |")
    w("|---|---|---|---|---|---|---|---|---|")
    for key, lab in [("sharov_mammals_0125", "Sharov, mammals at 0.125 Gya (his dating)"),
                     ("sharov_mammals_0_legacy_repo", "Sharov, mammals at 0 (old repo)"),
                     ("markov_published_ages", "Markov 2010, published ages"),
                     ("markov_current_ages", "Markov 2010, current ages"),
                     ("extended_corrected", "Extended set, corrected")]:
        r = rep[key]
        w(f"| {lab} | {r['n']} | {f(r['a'],3)} | {f(r['b'],3)} | {f(r['r2'],3)} | {f(r['fold_per_gyr'])} | "
          f"{f(r['origin_1bp'])} | {f(r['fieller95'][0])} to {f(r['fieller95'][1])} | "
          f"{f(r['fieller99'][0])} to {f(r['fieller99'][1])} |")
    rc_ = rep["readme_claims"]
    w(f"\nWith mammals at 0.125 Gya the intercept matches Sharov's printed {p['a']}; the old repo's "
      f"0.0 date caused the mismatch. The README's Markov R² of {rc_['markov_r2']} is not reproduced "
      f"(computed {f(rep['markov_published_ages']['r2'],3)}). Updating clade ages to current estimates lowers "
      f"R² to {f(rep['markov_current_ages']['r2'],3)} and moves the origin to "
      f"{f(rep['markov_current_ages']['origin_1bp'])} Gya; sampling ages uniformly within current ranges gives "
      f"a 95% range of {f(s['current_age_sampling']['p2_5'])} to {f(s['current_age_sampling']['p97_5'])} Gya "
      f"from age uncertainty alone.\n")

    w("## 2. Within-model uncertainty is small; the straight line itself fails\n")
    ys, ym = eiv["york_sharov"], eiv["york_markov"]
    w(f"- **Inside the straight-line model the pre-Earth date is statistically firm.** Even the 99% Fieller "
      f"interval for Sharov's data starts at {f(rep['sharov_mammals_0125']['fieller99'][0])} Gya.")
    w(f"- **York errors-in-variables fit, using the repo's assumed error bars:** Sharov χ² = {f(ys['chi2'],1)} "
      f"on {ys['dof']} df (p = {f(ys['p_line_fits'],2)}, line acceptable); Markov χ² = {f(ym['chi2'],1)} on "
      f"{ym['dof']} df (p = {ym['p_line_fits']:.1e}). **A constant-rate line is rejected for Markov's nine points.**")
    dem = eiv["deming_sharov"]
    w(f"- **Deming regression** (any ratio of age error to size error) keeps Sharov's origin between "
      f"{f(min(d['origin_1bp'] for d in dem))} and {f(max(d['origin_1bp'] for d in dem))} Gya.")
    at = eiv["attenuation_route_sharov"]
    w(f"- **Measurement-error route to an Earth origin:** an attenuation-corrected slope puts the point "
      f"estimate at 4.5 Gya only if every clade age carries an error SD of about "
      f"{f(at['age_error_sd_for_origin_4p5'])} Gyr (reliability factor {f(at['reliability_factor_at_that_sd'])}), "
      f"including the 125 Ma mammal date. That factor is close to the λ ≈ 2.7 that Marzban et al. (2014) "
      f"report; whether it is the same quantity needs checking against their full text.\n")

    w("## 3. Curve shape: the best-fitting curve has no origin date\n")
    w("| Model (Markov, published ages) | k | RSS | AICc | Origin of 1 bp | Parameter at bound |")
    w("|---|---|---|---|---|---|")
    for name, r in s["curves"]["published"].items():
        if r.get("converged"):
            w(f"| {name} | {r['k']} | {f(r['rss'],3)} | {f(r['aicc'])} | "
              f"{f(r['origin_1bp']) + ' Gya' if r['origin_1bp'] else 'none'} | {'yes' if any(r['at_bounds']) else 'no'} |")
    be = s["curves"]["published"]["biexponential"]
    w(f"\nOf the four curves only the straight line reaches 1 bp. "
      f"Markov et al.'s own biexponential form fits best and levels off at about 10^{f(be['params'][0])} bp "
      f"in the deep past: it never reaches 1 bp. Models flagged \"at bound\" are degenerate fits.\n")
    bs = s["broken_stick"]["published"]
    w(f"A two-segment line breaks at {f(bs['break_gya'])} Gya with rates {f(bs['rate_old'])} (older) and "
      f"{f(bs['rate_young'])} (younger) log10/Gyr. AICc {f(bs['aicc_two_segment'])} against "
      f"{f(bs['aicc_one_line'])} for one line, or {f(bs['aicc_two_segment_with_break_param'])} if the "
      f"breakpoint is also penalised as a parameter.\n")

    w("## 4. Rate constancy\n")
    ph, pre = rc["phanerozoic_fit"], rc["precambrian_fit"]
    w(f"- Phanerozoic points only: rate {f(ph['b'])}, origin {f(ph['origin_1bp'])} Gya. Its predictions for the "
      f"older points miss by " + ", ".join(f"{q['group']} {q['error_log10']:+.1f}" for q in ph["predictions"]) +
      " orders of magnitude.")
    w(f"- Precambrian points only: rate {f(pre['b'])}, origin {f(pre['origin_1bp'])} Gya.")
    loo = rc["leave_one_out"]
    lo_ = min(loo, key=lambda r: r["origin"])
    hi_ = max(loo, key=lambda r: r["origin"])
    w(f"- Leave-one-out origins range from {f(lo_['origin'])} Gya (dropping {lo_['group']}) to "
      f"{f(hi_['origin'])} Gya (dropping {hi_['group']}).\n")

    w("## 5. The unobserved interval before the oldest point\n")
    w("Origin = first point age + (its log10 size) / (m × fitted rate). The data fix the fitted rate, not m.\n")
    w("| Anchor | Multiplier m for origin at 4.4 Gya | at 4.5 Gya | Doubling time needed (Myr) |")
    w("|---|---|---|---|")
    for key, lab in [("sharov_first_point", "Sharov prokaryote, 0.5 Mb at 3.5 Gya"),
                     ("markov_first_point", "Markov bacterium, 1.3 Mb at 4.0 Gya"),
                     ("luca_moody2024", "LUCA, 2.5 Mb at 4.2 Gya (Moody et al. 2024)")]:
        r = er[key]
        w(f"| {lab} | {f(r['required_multiplier_origin_4p4'],1)} | {f(r['required_multiplier_origin_4p5'],1)} | "
          f"{f(r['doubling_myr_at_4p4'],0)} |")
    a, b = er["observed_segment_rate_ratios_markov"]
    w(f"\nWithin the observed record, segment rates already differ from the average by factors of "
      f"{f(a)} to {f(b)}.\n")
    mr = s["metric_reductio"]
    w(f"The same constant-rate method applied to protein-coding gene counts puts the origin at "
      f"{f(mr['protein_coding_genes']['origin_of_one_unit_gya'],1)} Gya, and to constrained DNA at "
      f"{f(mr['constrained_dna_bp']['origin_of_one_unit_gya'],1)} Gya, both older than the universe (13.8).\n")

    w("## 6. Calibration on simulated histories (no clock unless stated)\n")
    st = c["settings"]
    w(f"Life starts at 10^{st['start_log10_bp']:.0f} bp, {st['root_age_gya']} Gya, so the true origin is on Earth. "
      f"{st['reps']} runs per setting; clade ages are Markov's. Parameters are illustrative.\n")
    inv = c["invariance"]
    w(f"**A uniform clock is invisible to the method.** In coupled runs (identical random numbers) the "
      f"nested-minimum slope is {f(inv['0.0']['nested_fit'][0],3)} without a clock and "
      f"{f(inv['0.8']['nested_fit'][0],3)} with a clock of +0.8 log10/Gyr. The true ancestral series "
      f"changes from {f(inv['0.0']['ancestor_fit'][0])} to {f(inv['0.8']['ancestor_fit'][0])}. Every living "
      f"genome carries the same total growth, so statistics computed only from living species shift by a "
      f"constant (this is checked exactly in `tests/test_simulate.py`).\n")
    w("| True clock rate | Method's fitted rate (median) | True ancestral rate (median) | Inferred origin (median, Gya) |")
    w("|---|---|---|---|")
    for t in c["trend_recovery"]:
        w(f"| {t['true_drift']} | {f(t['nested_slope_median'])} | {f(t['ancestor_slope_median'])} | "
          f"{f(t['inferred_origin_median'],1)} |")
    obs = c["observed_markov"]["slope"]
    w(f"\n**No-clock grid** (random focal lineage). Observed Markov slope: {f(obs)}.\n")
    w("| σ | λ | μ | Median tips | Fitted rate (median) | Median R² | Inferred origin | Share inferring pre-Earth |")
    w("|---|---|---|---|---|---|---|---|")
    for g in c["null_grid"]:
        if g["focal"] == "random":
            w(f"| {g['sigma']} | {g['lam']} | {g['mu']} | {g['median_tips']} | {f(g['nested_slope_median'])} | "
              f"{f(g['r2_median'])} | {f(g['inferred_origin_median'],1)} | {g['pre_earth_frac']*100:.0f}% |")
    w("\nThe share inferring pre-Earth depends on the assumed starting size and on σ and λ. What does not "
      "depend on them is that the method reports a positive rate, with high R², when there is no clock at all.")
    near = [g for g in c["null_grid"] if g["focal"] == "random" and abs(g["nested_slope_median"] - obs) < 0.1]
    if near:
        w(f"\nSettings whose no-clock slope is within 0.1 of the observed {f(obs)} infer a pre-Earth origin in "
          f"{min(g['pre_earth_frac'] for g in near)*100:.0f}% to {max(g['pre_earth_frac'] for g in near)*100:.0f}% "
          f"of runs, with median R² {f(min(g['r2_median'] for g in near))} to {f(max(g['r2_median'] for g in near))}.\n")
    mx = [g for g in c["null_grid"] if g["focal"] == "max"]
    w(f"**Choosing the most complex living lineage biases even the true ancestral series.** With no clock, "
      f"the ancestors of the maximum-genome lineage show median rates of "
      f"{f(min(g['ancestor_slope_median'] for g in mx))} to {f(max(g['ancestor_slope_median'] for g in mx))} "
      f"log10/Gyr across the grid, because selecting the endpoint selects the path.\n")
    fl = c["null_floor"]
    w(f"With a reflecting floor at 10^5.5 bp (random focal): fitted rate {f(fl['random']['nested_slope_median'])}, "
      f"median R² {f(fl['random']['r2_median'])}, inferred origin {f(fl['random']['inferred_origin_median'],1)} Gya.\n")

    real_path, prok_path = ROOT / "results" / "realdata.json", ROOT / "results" / "prokaryotes.json"
    if real_path.exists():
        realdata_section(json.load(open(real_path)), w)
    if prok_path.exists():
        prokaryote_section(json.load(open(prok_path)), w)

    w("## 9. What this means for the next stages\n")
    w("1. Statistics built only from living species (clade minima, maxima, representatives) cannot measure "
      "a uniform clock. Their slope reflects trait spread and diversification, and on the real animal tree a "
      "no-trend model reproduces the observed slopes.")
    w("2. The same argument means extant-only reconstructions on a time-calibrated tree cannot identify a "
      "uniform trend either, since every tip has evolved for the same time. WP4 needs fossil genome-size proxies "
      "or gene-family histories, which carry information about the past directly.")
    w("3. Focal lineages must be chosen without regard to their genome size, or the selection must be modelled.")
    w("4. Brownian motion fits plants poorly (whole-genome duplications inflate the rate). Bounded and "
      "jump models (Ornstein-Uhlenbeck, Lévy) are the next null models to fit.\n")

    (ROOT / "results" / "RESULTS.md").write_text("\n".join(L))
    print("wrote results/RESULTS.md")


def realdata_section(r, w):
    inp = r["inputs"]
    w("## 7. Real data (WP3)\n")
    w(f"Inputs: {inp['goat_species']:,} eukaryote species with directly measured genome sizes (GoaT), "
      f"{inp['tree_tips']:,}-tip Timetree of Life (2015), NCBI taxonomy. Raw files are not redistributed "
      f"(see `data/external/README.md`); rebuild them with `make fetch`. Sources: GoaT (Challis et al. 2023), "
      f"TimeTree (Hedges et al. 2015; Kumar et al. 2022), NCBI Taxonomy, GTDB (Parks et al.).\n")
    w("### 7.1 Markov et al.'s table rebuilt from current data\n")
    w("| Group | Species with size | Minimum (Mb) | Smallest species | 1st percentile (Mb) | Median (Mb) | "
      "TimeTree crown age (Gya) | Markov MGS (Mb) | Markov age (Gya) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for row in r["markov_recomputed"]["table"]:
        w(f"| {row['group']} | {row['n_species_with_size']:,} | {f(row['min_mb'])} | *{row['min_species']}* | "
          f"{f(row['p01_mb'],1)} | {f(row['median_mb'],0)} | {f(row['crown_age_gya_timetree'],3)} | "
          f"{f(row['markov_mgs_mb'],1)} | {f(row['markov_age_gya'],3)} |")
    fits = r["markov_recomputed"]["fits"]
    w("\n| Statistic tracked per clade | Rate (log10/Gyr) | R² | Implied origin of 1 bp (Gya) |")
    w("|---|---|---|---|")
    for key, lab in [("min_mb", "Minimum (Markov's statistic)"), ("p01_mb", "1st percentile"),
                     ("median_mb", "Median (typical genome)")]:
        w(f"| {lab} | {f(fits[key]['b'])} | {f(fits[key]['r2'])} | {f(fits[key]['origin_1bp'],1)} |")
    w("\nThe measured minima match Markov's values closely; the true eukaryote minimum is a parasitic "
      "microsporidian. The implied clock depends entirely on which statistic is tracked. Typical genomes "
      "barely change between nested clades: the trend lives in the extremes.\n")

    w("### 7.2 Every species as focal lineage, against a no-trend null on the same tree\n")
    w("For each species, the minimum genome size below each of its ancestral nodes is regressed on node age, "
      "as in Markov's construction. The null simulates Brownian motion with no trend on the same pruned "
      f"tree, at the rate estimated by independent contrasts ({r['calibration']['Metazoa']['null_bm']['runs']} runs).\n")
    w("| Tree | Tips | σ (log10/√Gyr) | Observed rate, median (IQR) | Observed R² | Null rate, median of runs (range) | "
      "Null R² | Share pre-Earth: observed / null |")
    w("|---|---|---|---|---|---|---|---|")
    for name in ("Eukaryota", "Metazoa", "Viridiplantae"):
        c = r["calibration"][name]
        o, n = c["observed"], c["null_bm"]
        med = sorted(n["slope_median"])[len(n["slope_median"]) // 2]
        w(f"| {name} | {c['tips']:,} | {f(c['sigma_log10_per_sqrt_gyr'])} | {f(o['slope_median'])} "
          f"({f(o['slope_iqr'][0])} to {f(o['slope_iqr'][1])}) | {f(o['r2_median'])} | {f(med)} "
          f"({f(min(n['slope_median']))} to {f(max(n['slope_median']))}) | "
          f"{f(sorted(n['r2_median'])[len(n['r2_median']) // 2])} | "
          f"{o['pre_earth_frac']*100:.0f}% / {sorted(n['pre_earth_frac'])[len(n['pre_earth_frac']) // 2]*100:.0f}% |")
    w("\nIn animals the observed rates fall inside the no-trend range. In plants the Brownian null overshoots, "
      "because whole-genome duplications inflate the rate estimate; the observed plant rates are lower than "
      "a trendless random walk would give, which is the opposite of what a clock would add.\n")
    w("**Different lineages imply different origins.** Median implied origin by focal clade:\n")
    w("| Focal clade | Focal species | Median rate | Median implied origin (Gya) | IQR |")
    w("|---|---|---|---|---|")
    for row in r["calibration"]["origin_by_focal_clade"]:
        w(f"| {row['clade']} | {row['focal_lineages']:,} | {f(row['slope_median'])} | {f(row['origin_median'],1)} | "
          f"{f(row['origin_iqr'][0],1)} to {f(row['origin_iqr'][1],1)} |")
    meds = [row["origin_median"] for row in r["calibration"]["origin_by_focal_clade"]]
    w(f"\nA universal clock would give one date. These span {f(max(meds) - min(meds), 1)} Gyr "
      f"({f(min(meds), 1)} to {f(max(meds), 1)} Gya); estimates above 13.8 are older than the universe.\n")


def prokaryote_section(p, w):
    w("## 8. Prokaryotes: has the genome grown since LUCA? (WP3)\n")
    w(f"GTDB {p['gtdb_version']}: {p['filters']}. LUCA estimate: "
      f"{p['luca_mb_interval'][0]} to {p['luca_mb_interval'][1]} Mb about 4.2 Gya (Moody et al. 2024).\n")
    w("| Set | Species | 5% | Median | 95% | Max | Share smaller than LUCA (2.49 / 2.99 Mb) |")
    w("|---|---|---|---|---|---|---|")
    rows = [("Bacteria, all", p["bacteria"]["all"]), ("Bacteria, isolates", p["bacteria"]["isolates"]),
            ("Archaea, all", p["archaea"]["all"]), ("Archaea, isolates", p["archaea"]["isolates"]),
            ("All prokaryote isolates", p["all_prokaryotes_isolates"])]
    for lab, d in rows:
        w(f"| {lab} | {d['n']:,} | {f(d['q05_mb'])} | {f(d['q50_mb'])} | {f(d['q95_mb'])} | {f(d['max_mb'])} | "
          f"{d['frac_below_luca_low']*100:.0f}% / {d['frac_below_luca_high']*100:.0f}% |")
    rate = p["implied_rate_luca_to_present_log10_per_gyr"]
    w(f"\nLUCA's genome sits inside the modern range. Growth from LUCA to the median modern isolate implies "
      f"{f(rate,3)} log10/Gyr, a doubling about every {f(0.30103 / rate, 1)} Gyr, against Sharov's 0.89 "
      f"(every 0.34 Gyr). Across 4.2 Gyr of prokaryotic evolution the typical genome has changed little, as "
      f"Koonin argued in 2006. This does not exclude growth followed by reduction, but it leaves no room for a "
      f"steady clock in the prokaryotic era.\n")


if __name__ == "__main__":
    main()
